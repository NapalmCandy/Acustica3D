import { chromium } from '/home/user/acustica3d/acustica3d/node_modules/playwright/index.mjs';
const [URL, FILE, OUT] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
await p.goto(URL);
await p.setInputFiles('#model-file', FILE);
await p.waitForSelector('text=/^Hecho: /', { timeout: 900000 });
const li = p.locator('li', { hasText: 'Madera DM' }).first();
await li.locator('input[type=checkbox]').uncheck();
console.log('mesa:', await li.locator('select').inputValue());
await p.waitForTimeout(500);
await p.waitForSelector('text=/^Hecho: /', { timeout: 900000 });
await p.click('role=tab[name="Colocación automática"]');
await p.locator('label', { hasText: 'Precisión' }).locator('select').selectOption('rapida');
console.log('tratamiento marcado:', await p.locator('label', { hasText: 'Mover también trampas' }).locator('input').isChecked());
await p.click('button:has-text("Buscar la mejor colocación")');
await p.waitForSelector('text=/posición \\d+ de ~\\d+/', { timeout: 300000 });
await p.waitForTimeout(15000);
console.log('estado:', await p.locator('text=/posición \\d+ de ~\\d+/').first().innerText());
console.log('error:', await p.locator('#opt-error').count());
await p.screenshot({ path: OUT + '/smoke.png' });
await li.locator('input[type=checkbox]').check();
console.log('mesa otra vez:', await li.locator('select').inputValue());
await b.close();
