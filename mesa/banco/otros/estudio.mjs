import { chromium } from '/home/user/acustica3d/acustica3d/node_modules/playwright/index.mjs';
const [URL, FILE, OUT] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
await p.goto(URL);
await p.waitForSelector('h1:has-text("Acustica3D")');
await p.setInputFiles('#model-file', FILE);
await p.waitForSelector('text=/^Hecho: /', { timeout: 900000 });
console.log('notas:\n' + (await p.locator('aside p.bg-accent\\/10').allInnerTexts()).join('\n'));
console.log('avisos:', (await p.locator('aside p.bg-amber-500\\/10').allInnerTexts()).join(' | '));
console.log('fuga:', await p.locator('text=no está cerrada').count());
console.log(await p.locator('text=/^Motor: /').innerText());
await p.click('role=tab[name="Mejor posición"]');
await p.waitForTimeout(800);
console.log('mejor:', (await p.locator('#best-score').innerText()).replace(/\n/g, ' '), await p.locator('#best-pos').innerText(), '· tú:', await p.locator('#you-score').innerText());
await p.screenshot({ path: OUT + '/estudio_mejor.png' });
await b.close();
