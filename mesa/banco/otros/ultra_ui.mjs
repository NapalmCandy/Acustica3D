import { chromium } from '/home/user/acustica3d/acustica3d/node_modules/playwright/index.mjs';
const [URL, FILE, OUT, WAIT = '180'] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
await p.goto(URL);
await p.setInputFiles('#model-file', FILE);
await p.waitForSelector('text=/^Hecho: /', { timeout: 900000 });
await p.click('role=tab[name="Colocación automática"]');
await p.locator('label', { hasText: 'Precisión' }).locator('select').selectOption('ultra');
await p.screenshot({ path: OUT + '/ultra_opciones.png' });
await p.click('button:has-text("Buscar la mejor colocación")');
const t0 = Date.now();
await p.waitForTimeout(Number(WAIT) * 1000);
console.log('fase a los', WAIT, 's:', await p.locator('text=/posición \\d+ de/').innerText().catch(() => '?'));
await p.click('#opt-stop');
await p.waitForSelector('text=/^Terminado en/', { timeout: 900000 });
console.log(await p.locator('text=/^Terminado en/').innerText(), '·', ((Date.now() - t0) / 1000).toFixed(0), 's');
console.log((await p.locator('#opt-top').innerText()).split('\n').slice(0, 8).join('\n'));
await p.screenshot({ path: OUT + '/ultra_fin.png' });
await b.close();
